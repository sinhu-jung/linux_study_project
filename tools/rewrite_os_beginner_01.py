def run():
    additions = {}
    for path in (ROOT/'course/lesson-parts').glob('*.json'):
        for l in json.loads(path.read_text(encoding='utf-8')):
            if l['id'] not in ROWS:
                continue
            practice = dict(l.get('practice',{}))
            practice['expected'] = EXPECTED[l['id']]
            # Replace old auxiliary prose as well; original is retained in technical_original.
            additions[l['id']] = dict(concepts=[], reading_support=None,
                experiment={'title':'말로 확인해 보기','steps':[
                    ROWS[l['id']][2], '직접 그린 그림과 위 설명을 비교하세요. 답만 말하지 말고 왜 그런지도 한 문장으로 말해 보세요.']},
                practice=practice)
    return rewrite(ROWS,'tools/rewrite_os_beginner_01.py',additions)


if __name__ == '__main__':
    print(json.dumps(run(),ensure_ascii=False))
