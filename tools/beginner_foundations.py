def apply(lessons):
    """Rewrite the introduction layer; retain exact prior material for comparison."""
    mapping = {f'cs{i:02d}': row for i, row in enumerate(ROWS, 1)}
    for lesson in lessons:
        row = mapping.get(lesson['id'])
        if row is None:
            continue
        if len(lesson['questions']) != 2:
            raise ValueError('Foundation question count changed: ' + lesson['id'])
        story, meaning, exercise, *answers = row
        lesson['beginner'] = {'story': story, 'meaning': meaning, 'exercise': exercise,
                             'review': '입문 설명과 두 문제의 풀이를 쉬운 말로 다시 작성했습니다. 실제 어린이의 이해도 시험은 아직 하지 않았습니다.'}
        index = int(lesson['id'][2:])-1
        for q, explanation, prompt, options in zip(lesson['questions'], answers, PROMPTS[index], OPTIONS[index]):
            q.setdefault('original_explanation', q['explanation'])
            q.setdefault('original_prompt', q['prompt'])
            q.setdefault('original_options', q['options'])
            q['prompt'] = prompt
            q['options'] = options
            q['explanation'] = explanation
