def run():
    additions={}
    for path in (ROOT/'course/lesson-parts').glob('*.json'):
        for lesson in json.loads(path.read_text(encoding='utf-8')):
            key=lesson['id']
            if key not in ROWS: continue
            practice=dict(lesson.get('practice',{})); practice['expected']=ROWS[key][2]
            additions[key]=dict(concepts=[],reading_support=None,deep_dive=[],goal=ROWS[key][1],experiment={'title':'종이에 따라 해 보기','steps':[ROWS[key][2]]},practice=practice)
    return rewrite(ROWS,'tools/rewrite_os_beginner_192.py',additions)
if __name__=='__main__': print(json.dumps(run(),ensure_ascii=False))
